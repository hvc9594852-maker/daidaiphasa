def fig(inner, cap='', narrow=False, plate=True):
    c = f'<p class="figcap">{cap}</p>' if cap else ''
    return f'<figure class="fig{" narrow" if narrow else ""}"><div class="{"plate" if plate else ""}">{inner}</div>{c}</figure>'
def pq(t): return f'<blockquote class="pq"><p>{t}</p></blockquote>'
def spec(head_row, rows, center=(), thcol=(0,)):
    th = ''.join(f'<th{" class=c" if i in center else ""}>{h}</th>' for i, h in enumerate(head_row))
    def td(i, c):
        cls = ' '.join(x for x in ('c' if i in center else '', 'th' if i in thcol else '') if x)
        return f'<td{f" class={chr(34)}{cls}{chr(34)}" if cls else ""}>{c}</td>'
    trs = ''.join('<tr>' + ''.join(td(i, c) for i, c in enumerate(r)) + '</tr>' for r in rows)
    return f'<div class="scroll"><table class="spec"><thead><tr>{th}</tr></thead><tbody>{trs}</tbody></table></div>'
def chips(items, cls='', big=False):
    return f'<ul class="chips{" big" if big else ""}">' + ''.join(f'<li><b>{a}</b><span class="{cls}">{b}</span></li>' for a, b in items) + '</ul>'
def pairs(rows, hl='บนจอ', hr='ที่ตั้งใจพิมพ์'):
    out = f'<div class="h l">{hl}</div><div class="h a"></div><div class="h r">{hr}</div>'
    for l, r in rows: out += f'<div class="l">{l}</div><div class="a">→</div><div class="r">{r}</div>'
    return f'<div class="pairs">{out}</div>'

