def place(name, kind, rows, note='', src=''):
    dl = ''.join(f'<dt>{k}</dt><dd>{v}</dd>' for k, v in rows)
    n = f'<p class="pnote">{note}</p>' if note else ''
    s = f'<p class="psrc">ที่มาข้อมูล: {src}</p>' if src else ''
    return f'<section class="place"><p class="ptype">{kind}</p><h3>{name}</h3><dl>{dl}</dl>{n}{s}</section>'

def lnk(u, t): return f'<a href="{u}" rel="noopener">{t}</a>'

def compare(head, rows):
    th = ''.join(f'<th>{h}</th>' for h in head)
    tr = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows)
    return f'<div class="scroll"><table class="spec"><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table></div>'

